// Rebuild after changing nota_avalia.json or the PNG assets:
// node Banner/build-local-resources.cjs
const fs = require('node:fs');
const path = require('node:path');

const notes = JSON.parse(fs.readFileSync(path.join(__dirname, 'nota_avalia.json'), 'utf8').replace(/^\uFEFF/, ''));
const images = {};
for (const directory of ['assets', 'Selo', 'logos_sites_padronizadas', 'tipos de banner Sem Fundo']) {
  for (const name of fs.readdirSync(path.join(__dirname, directory)).sort()) {
    if (!name.endsWith('.png')) continue;
    images[`${directory}/${name}`] = `data:image/png;base64,${fs.readFileSync(path.join(__dirname, directory, name)).toString('base64')}`;
  }
}
fs.writeFileSync(path.join(__dirname, 'dados-locais.js'),
  '// Generated by build-local-resources.cjs. Do not edit directly.\n'
  + `globalThis.__BANNER_LOCAL_DATA__ = ${JSON.stringify({ notes, images })};\n`, 'utf8');
console.log(`Recursos locais atualizados: ${notes.length} entidades e ${Object.keys(images).length} imagens.`);
